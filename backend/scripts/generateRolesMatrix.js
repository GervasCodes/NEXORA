#!/usr/bin/env node
/**
 * Generates docs/design/roles-matrix.generated.md from the route inventory: for every module, how many
 * routes are public, need only a login, or are limited to each role, plus every route that has NO guard
 * at all (the list to review first). Run: node scripts/generateRolesMatrix.js
 *
 * Static analysis only: checks done inside a controller or service (such as "only the owner of this
 * order") are not visible here; they are covered by tests/unit/ownership.test.js.
 */
const fs = require("fs");
const path = require("path");
const { buildInventory } = require("./routeInventory");

const OUT = path.join(__dirname, "..", "..", "docs", "design", "roles-matrix.generated.md");
const ROLES = ["buyer", "seller", "delivery_agent", "admin"];

const classify = (route) => {
    const roles = route.guards.filter((g) => g.startsWith("role:")).map((g) => g.slice(5));
    if (roles.length) return { kind: "roles", roles };
    if (route.guards.includes("auth")) return { kind: "login" };
    if (route.guards.some((g) => /^verify.*Webhook|^webhook/i.test(g))) return { kind: "webhook" };
    return { kind: "public" };
};

const build = () => {
    const routes = buildInventory();
    const modules = {};
    const open = [];
    for (const r of routes) {
        const m = (modules[r.module] ||= { public: 0, webhook: 0, login: 0, ...Object.fromEntries(ROLES.map((x) => [x, 0])) });
        const c = classify(r);
        if (c.kind === "roles") c.roles.forEach((x) => { if (x in m) m[x] += 1; });
        else m[c.kind] += 1;
        if (c.kind === "public" && r.method !== "GET") open.push(r);
    }
    const rows = Object.entries(modules).sort(([a], [b]) => a.localeCompare(b))
        .map(([name, m]) => `| ${name} | ${m.public || ""} | ${m.webhook || ""} | ${m.login || ""} | ${ROLES.map((x) => m[x] || "").join(" | ")} |`);
    const openRows = open.sort((a, b) => a.path.localeCompare(b.path))
        .map((r) => `| ${r.method} | \`${r.path}\` | ${r.module} | ${r.guards.join(", ") || "none"} |`);
    return [
        "# Roles matrix (generated)",
        "",
        "> Generated by `backend/scripts/generateRolesMatrix.js` from the route files. Do not edit by hand;",
        "> re-run the script. Counts are declared routes per guard, not effective permissions: ownership",
        "> checks inside services are not visible here (see `backend/tests/unit/ownership.test.js`).",
        "> A route with several roles counts once per role.",
        "",
        `Total routes under /api/v1: **${routes.length}**.`,
        "",
        "| Module | Public | Webhook (signature) | Any signed-in | Buyer | Seller | Delivery agent | Admin |",
        "|---|---|---|---|---|---|---|---|",
        ...rows,
        "",
        "## Public routes that change data (non-GET, no login)",
        "",
        "Review each: it should be sign-up/sign-in, a public form with a limiter, or a webhook.",
        "",
        "| Method | Path | Module | Guards |",
        "|---|---|---|---|",
        ...openRows,
        ""
    ].join("\n");
};

module.exports = { build };

if (require.main === module) {
    fs.writeFileSync(OUT, build());
    console.log(`Wrote ${path.relative(path.join(__dirname, "..", ".."), OUT)}`);
}
