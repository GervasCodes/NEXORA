#!/usr/bin/env node
/**
 * Keeps docs/openapi.yaml in step with the routes the backend really declares.
 *
 *   node scripts/syncOpenApi.js                  check only: lists drift, exits 1 if there is any (use in CI)
 *   node scripts/syncOpenApi.js --write          adds a stub for every route that is missing from the spec
 *   node scripts/syncOpenApi.js --write --prune  also removes spec operations that have no route any more
 *
 * A stub states the facts that can be read from the code (method, path, module tag, path parameters, the
 * guards in front of the route and so whether it needs a login) and says plainly, with
 * `x-contract-documented: false`, that the request and response contract has not been written yet. It never
 * invents field lists. Replace a stub with the real contract (from the module's *.validator.js and
 * *.controller.js) when you work on that endpoint; the synchroniser will not touch an operation that
 * already exists.
 *
 * Paths in the spec are relative to the `servers` URL (which ends in /api/v1), so they never start with
 * /api/v1 themselves.
 */
const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");
const { buildInventory, normalise, API_PREFIX } = require("./routeInventory");

const SPEC_FILE = path.join(__dirname, "..", "..", "docs", "openapi.yaml");
const METHODS = ["get", "post", "put", "patch", "delete"];

const relative = (p) => (p.startsWith(API_PREFIX) ? p.slice(API_PREFIX.length) || "/" : p);
const keyOf = (method, p) => `${method.toUpperCase()} ${normalise(relative(p))}`;

const words = (name) => String(name || "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[_-]+/g, " ").trim().toLowerCase();
const sentence = (text) => text.charAt(0).toUpperCase() + text.slice(1);

const needsLogin = (guards) => guards.some((g) => g === "auth" || g.startsWith("role:"));
const roles = (guards) => guards.filter((g) => g.startsWith("role:")).map((g) => g.slice(5));

const stub = (route, usedIds, specPath) => {
    const base = `${route.module}_${route.handler || route.method.toLowerCase()}`;
    let operationId = base;
    for (let n = 2; usedIds.has(operationId); n += 1) operationId = `${base}_${n}`;
    usedIds.add(operationId);

    // Equivalent templates must share parameter names in OpenAPI (/x/{id} and /x/{pageKey} are the same
    // path), so name the parameters after the path item this operation joins, position by position.
    const routeNames = [...route.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    const specNames = [...specPath.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    const parameters = specNames.map((name, i) => ({
        name, in: "path", required: true, schema: { type: "string" },
        ...(routeNames[i] && routeNames[i] !== name ? { description: `Called :${routeNames[i]} in this route.` } : {})
    }));
    const protectedRoute = needsLogin(route.guards);
    const responses = { 200: { description: "Success. Response contract not documented yet." } };
    if (protectedRoute) responses[401] = { description: "Not signed in, or the session is no longer valid." };
    if (roles(route.guards).length || route.guards.some((g) => /^require/.test(g))) {
        responses[403] = { description: "Signed in, but this role or account state is not allowed to do this." };
    }

    const operation = {
        tags: [route.module],
        summary: sentence(words(route.handler) || `${route.method} ${route.path}`),
        description:
            `Stub generated by scripts/syncOpenApi.js from ${route.file}. The request and response contract is NOT ` +
            "documented yet; read the module's validator and controller. Guards found in front of this route: " +
            `${route.guards.length ? route.guards.join(", ") : "none (public, or protected inside the handler)"}.`,
        operationId,
        "x-contract-documented": false,
        "x-guards": route.guards,
        ...(parameters.length ? { parameters } : {}),
        security: protectedRoute ? [{ bearerAuth: [] }] : [],
        responses
    };
    return operation;
};

const load = () => yaml.load(fs.readFileSync(SPEC_FILE, "utf8"));

const run = ({ write, prune }) => {
    const spec = load();
    const inventory = buildInventory();
    const codeKeys = new Map(inventory.map((r) => [keyOf(r.method, r.path), r]));

    // Existing spec operations, keyed the same way.
    const specKeys = new Map();
    for (const [p, item] of Object.entries(spec.paths || {})) {
        for (const method of METHODS) if (item[method]) specKeys.set(keyOf(method, p), { path: p, method });
    }

    const missing = [...codeKeys.keys()].filter((k) => !specKeys.has(k));
    const stale = [...specKeys.keys()].filter((k) => !codeKeys.has(k));

    if (!write) return { missing, stale, spec: null };

    const usedIds = new Set();
    Object.values(spec.paths || {}).forEach((item) => METHODS.forEach((m) => item[m]?.operationId && usedIds.add(item[m].operationId)));

    // Path items keyed by normalised path, so an operation joins the existing path item when there is one.
    const itemFor = new Map();
    for (const p of Object.keys(spec.paths || {})) itemFor.set(normalise(relative(p)), p);

    for (const key of missing) {
        const route = codeKeys.get(key);
        const rel = relative(route.path);
        const normal = normalise(rel);
        const specPath = itemFor.get(normal) || rel;
        spec.paths[specPath] = spec.paths[specPath] || {};
        spec.paths[specPath][route.method.toLowerCase()] = stub(route, usedIds, specPath);
        itemFor.set(normal, specPath);
    }

    if (prune) {
        for (const key of stale) {
            const { path: p, method } = specKeys.get(key);
            delete spec.paths[p][method];
            if (!METHODS.some((m) => spec.paths[p][m])) delete spec.paths[p];
        }
    }

    // Every tag in use must be declared.
    const declared = new Set((spec.tags || []).map((t) => t.name));
    const used = new Set();
    Object.values(spec.paths).forEach((item) => METHODS.forEach((m) => (item[m]?.tags || []).forEach((t) => used.add(t))));
    spec.tags = spec.tags || [];
    [...used].filter((t) => !declared.has(t)).sort().forEach((name) => spec.tags.push({ name, description: `${name} endpoints (tag added by scripts/syncOpenApi.js).` }));

    spec.paths = Object.fromEntries(Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b)));
    fs.writeFileSync(SPEC_FILE, yaml.dump(spec, { lineWidth: -1, noRefs: true, sortKeys: false }));
    return { missing, stale, spec };
};

exports.run = run;
exports.SPEC_FILE = SPEC_FILE;
exports.load = load;

if (require.main === module) {
    const write = process.argv.includes("--write");
    const prune = process.argv.includes("--prune");
    const { missing, stale } = run({ write, prune });
    if (write) {
        console.log(`Added ${missing.length} stub operation(s)${prune ? `, removed ${stale.length} stale operation(s)` : ""}.`);
        if (!prune && stale.length) console.log(`${stale.length} spec operation(s) have no route (run with --prune to remove them).`);
    } else {
        console.log(`Routes missing from the spec: ${missing.length}`);
        missing.slice(0, 30).forEach((k) => console.log(`  + ${k}`));
        console.log(`Spec operations with no route: ${stale.length}`);
        stale.slice(0, 30).forEach((k) => console.log(`  - ${k}`));
        process.exit(missing.length || stale.length ? 1 : 0);
    }
}
