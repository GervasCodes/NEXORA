#!/usr/bin/env node
/**
 * Generates schema documentation from a MIGRATED database (information_schema), so it cannot drift:
 *   docs/technical/data-dictionary.generated.md   every table and column: type, null, default, key, comment
 *   docs/diagrams/database-erd.generated.mmd      Mermaid ER diagram of the foreign keys
 *
 * Needs a database that already has the migrations applied (never point it at production):
 *   DB_HOST=127.0.0.1 DB_USER=test DB_PASSWORD=test DB_NAME=nexora_test node migrate.js
 *   DB_HOST=127.0.0.1 DB_USER=test DB_PASSWORD=test DB_NAME=nexora_test node generate-schema-docs.js
 *
 * Reads only information_schema; it never reads row data. Sensitivity labels come from the name-based
 * rules in SENSITIVE below and are a starting point for review, not a classification.
 */
const fs = require("fs");
const path = require("path");
const mysql = require("mysql2/promise");

const DOCS = path.join(__dirname, "..", "docs");
const SENSITIVE = [
    [/password|otp|token|secret|api_key|private_key/i, "secret"],
    [/phone|email|address|latitude|longitude|national_id|voter_id|tin\b|payout|account_number|ip_address/i, "personal"],
    [/amount|balance|price|fee|total|commission|earning/i, "financial"]
];
const sensitivity = (name) => (SENSITIVE.find(([re]) => re.test(name)) || [null, ""])[1];
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

(async () => {
    const connection = await mysql.createConnection({
        host: process.env.DB_HOST || "127.0.0.1",
        port: Number(process.env.DB_PORT || 3306),
        user: process.env.DB_USER,
        password: process.env.DB_PASSWORD,
        database: process.env.DB_NAME
    });
    try {
        const [[{ db }]] = await connection.query("SELECT DATABASE() AS db");
        const [[{ version }]] = await connection.query("SELECT VERSION() AS version");
        const [columns] = await connection.query(
            `SELECT TABLE_NAME AS t, COLUMN_NAME AS c, COLUMN_TYPE AS type, IS_NULLABLE AS nullable,
                    COLUMN_DEFAULT AS def, COLUMN_KEY AS ckey, EXTRA AS extra, COLUMN_COMMENT AS comment
             FROM information_schema.COLUMNS
             WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME, ORDINAL_POSITION`, [db]);
        const [fks] = await connection.query(
            `SELECT k.TABLE_NAME AS child, k.COLUMN_NAME AS col, k.REFERENCED_TABLE_NAME AS parent,
                    k.REFERENCED_COLUMN_NAME AS pcol, r.DELETE_RULE AS onDelete
             FROM information_schema.KEY_COLUMN_USAGE k
             JOIN information_schema.REFERENTIAL_CONSTRAINTS r
               ON r.CONSTRAINT_SCHEMA = k.TABLE_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME
             WHERE k.TABLE_SCHEMA = ? AND k.REFERENCED_TABLE_NAME IS NOT NULL
             ORDER BY k.TABLE_NAME, k.COLUMN_NAME`, [db]);
        const [tables] = await connection.query(
            "SELECT TABLE_NAME AS t, TABLE_COMMENT AS comment FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME", [db]);

        const fkOf = new Map(fks.map((f) => [`${f.child}.${f.col}`, f]));
        const byTable = new Map();
        for (const col of columns) (byTable.get(col.t) || byTable.set(col.t, []).get(col.t)).push(col);

        const out = [
            "# Data dictionary (generated)",
            "",
            "> Generated by `database/generate-schema-docs.js` from the migrated database. Do not edit by hand.",
            `> Server: ${version}. Tables: ${tables.length}. Columns: ${columns.length}. Foreign keys: ${fks.length}.`,
            "> Sensitivity (secret / personal / financial) is a name-based starting point for review, not a classification.",
            ""
        ];
        for (const { t, comment } of tables) {
            out.push(`## ${t}`, "", ...(comment ? [esc(comment), ""] : []),
                "| Column | Type | Null | Default | Key | References | Sensitivity | Note |", "|---|---|---|---|---|---|---|---|");
            for (const c of byTable.get(t) || []) {
                const fk = fkOf.get(`${t}.${c.c}`);
                out.push(`| ${c.c} | \`${esc(c.type)}\` | ${c.nullable === "YES" ? "yes" : "no"} | ${c.def === null ? "" : `\`${esc(c.def)}\``} | ${c.ckey || ""}${c.extra ? ` ${esc(c.extra)}` : ""} | ${fk ? `${fk.parent}.${fk.pcol} (${fk.onDelete})` : ""} | ${sensitivity(c.c)} | ${esc(c.comment)} |`);
            }
            out.push("");
        }
        fs.writeFileSync(path.join(DOCS, "technical", "data-dictionary.generated.md"), out.join("\n"));

        const erd = ["erDiagram", ...[...new Set(fks.map((f) => `    ${f.parent} ||--o{ ${f.child} : "${f.col}"`))]];
        fs.writeFileSync(path.join(DOCS, "diagrams", "database-erd.generated.mmd"), erd.join("\n") + "\n");
        console.log(`Wrote data-dictionary.generated.md (${tables.length} tables, ${columns.length} columns) and database-erd.generated.mmd (${fks.length} relationships).`);
    } finally {
        await connection.end();
    }
})().catch((error) => { console.error(error.message); process.exit(1); });
